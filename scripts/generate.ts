// Reads openapi.json and writes src/schema.d.ts, src/modules/*.ts and src/client.ts.
// Run it with `bun run generate`. Never edit the files it writes.
import { mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import openapiTS, { astToString, type OpenAPI3 } from "openapi-typescript";

interface Parameter {
  required?: boolean;
}

interface Operation {
  summary: string;
  description?: string;
  deprecated?: boolean;
  parameters?: Parameter[];
}

interface Doc {
  paths: Record<string, { get: Operation }>;
}

const SPEC_FILE = "openapi.json";
const CLIENT_CLASS = "HikerApiClient";
const HEADER =
  "// Generated by scripts/generate.ts from openapi.json. Do not edit.\n";

// HikerAPI's descriptions use em dashes and a warning emoji. A comma and no emoji read the same.
const text = readFileSync(SPEC_FILE, "utf8")
  .replace(/ \u2014(?= |\\n)/g, ",")
  .replaceAll("\u26a0\ufe0f ", "");
const spec: OpenAPI3 = JSON.parse(text);
const doc: Doc = JSON.parse(text);

function words(name: string): string[] {
  return name.split(/[^a-zA-Z0-9]+/).filter(Boolean);
}

function pascalCase(name: string): string {
  return words(name)
    .map((word) => word[0].toUpperCase() + word.slice(1))
    .join("");
}

function camelCase(name: string): string {
  const pascal = pascalCase(name);
  return pascal[0].toLowerCase() + pascal.slice(1);
}

// HikerAPI puts a version or a data source in front of the path: v1, v2, v3, gql, g1, g2, a2.
// "sys" is not one of them: it is the group of /sys/balance.
const SOURCE_PREFIX = /^(?:[vga]\d+|gql)$/;

// The group is the first word of the path and the method is the rest, so the name is the URL:
//   /v2/user/by/username  ->  user.byUsernameV2
//   /gql/user/medias      ->  user.mediasGql
//   /a2/user              ->  user.getA2  (nothing is left of the path, so it is "get")
//   /sys/balance          ->  sys.balance
// The same call exists under several prefixes, and a prefix is never dropped. Dropping one gives
// the plain name to whichever endpoint is lowest, which is often a deprecated one, and renames
// a method when HikerAPI adds a sibling.
function nameOf(path: string): { group: string; method: string } {
  const [first, ...rest] = path.split("/").filter(Boolean);
  const hasPrefix = SOURCE_PREFIX.test(first);
  const [group, ...tail] = hasPrefix ? rest : [first, ...rest];
  const suffix = hasPrefix ? pascalCase(first) : "";
  return { group, method: `${camelCase(tail.join("/") || "get")}${suffix}` };
}

function docComment(op: Operation): string {
  const lines = [op.summary];
  if (op.description && op.description !== op.summary)
    lines.push(op.description);
  if (op.deprecated)
    lines.push("@deprecated HikerAPI lists this endpoint as legacy.");
  const body = lines.join("\n\n").replaceAll("*/", "*\\/");
  return `/**\n${body
    .split("\n")
    .map((line) => ` * ${line}`.trimEnd())
    .join("\n")}\n */`;
}

interface Method {
  name: string;
  path: string;
  op: Operation;
}

const groups = new Map<string, Method[]>();
for (const [path, { get: op }] of Object.entries(doc.paths)) {
  const { group, method: name } = nameOf(path);
  const methods = groups.get(group) ?? [];
  if (methods.some((method) => method.name === name)) {
    throw new Error(
      `Two paths in "${group}" are named "${name}". Change nameOf to tell them apart.`,
    );
  }
  methods.push({ name, path, op });
  groups.set(group, methods);
}

function renderMethod({ name, path, op }: Method): string {
  const params = op.parameters ?? [];
  const args = ["options?: CallOptions"];
  let call = `this.http.get("${path}", undefined, options)`;
  if (params.length) {
    const optional = params.some((param) => param.required) ? "" : "?";
    args.unshift(`query${optional}: Query<"${path}">`);
    call = `this.http.get("${path}", query, options)`;
  }
  return `${docComment(op)}\n${name}(${args.join(", ")}) {\n  return ${call};\n}`;
}

function renderModule(group: string, methods: Method[]): string {
  const needsQuery = methods.some(({ op }) => op.parameters?.length);
  const http = needsQuery
    ? "type CallOptions, type Query, type Transport"
    : "type CallOptions, type Transport";
  return `${HEADER}import { ${http} } from "../http";

export class ${pascalCase(group)}Module {
  constructor(private readonly http: Transport) {}

${methods.map(renderMethod).join("\n\n")}
}
`;
}

function renderClient(groupNames: string[]): string {
  const modules = groupNames.map((name) => ({
    name,
    className: `${pascalCase(name)}Module`,
  }));
  return `${HEADER}import { Transport, type HikerApiConfig } from "./http";
${modules.map(({ name, className }) => `import { ${className} } from "./modules/${name}";`).join("\n")}

export class ${CLIENT_CLASS} {
${modules.map(({ name, className }) => `  readonly ${name}: ${className};`).join("\n")}

  constructor(config: HikerApiConfig | string) {
    const http = new Transport(typeof config === "string" ? { accessKey: config } : config);
${modules.map(({ name, className }) => `    this.${name} = new ${className}(http);`).join("\n")}
  }
}
`;
}

rmSync("src/modules", { recursive: true, force: true });
mkdirSync("src/modules", { recursive: true });
writeFileSync("src/schema.d.ts", astToString(await openapiTS(spec)));
for (const [group, methods] of groups) {
  writeFileSync(`src/modules/${group}.ts`, renderModule(group, methods));
}
writeFileSync("src/client.ts", renderClient([...groups.keys()]));
console.log(
  [...groups]
    .map(([group, methods]) => `${group}: ${methods.length}`)
    .join(", "),
);
